/** 指定した日（YYYY-MM-DD）以降の更新を、新しい順に */
export function changelogSince(since: string, until?: string): ChangelogEntry[] {
  return CHANGELOG
    .filter((e) => e.date >= since && (!until || e.date <= until))
    .sort((a, b) => (a.date === b.date ? 0 : a.date < b.date ? 1 : -1));
}
